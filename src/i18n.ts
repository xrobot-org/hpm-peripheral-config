export type Locale = 'en' | 'zh-cn';

let activeLocale: Locale = 'en';

function resolveLocale(language: string): Locale {
  const normalized = language.trim().toLowerCase().replace(/_/g, '-');
  return normalized === 'zh' || normalized === 'zh-cn' || normalized.startsWith('zh-hans')
    ? 'zh-cn'
    : 'en';
}

function catalog(locale: Locale): Record<MessageKey, string> {
  return locale === 'zh-cn' ? simplifiedChineseMessages : englishMessages;
}

export function setLocale(language: string): void {
  activeLocale = resolveLocale(language);
}

export function currentLocale(): Locale {
  return activeLocale;
}

export function messagesForLocale(language: string): Readonly<Record<MessageKey, string>> {
  return catalog(resolveLocale(language));
}

export function t(key: MessageKey, params: MessageParams = {}): string {
  const selected = catalog(activeLocale);
  const template = selected[key] ?? englishMessages[key] ?? key;
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (placeholder, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder
  ));
}


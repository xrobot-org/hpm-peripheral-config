export function diagnosticMessage(diagnostic: Pick<
  Diagnostic,
  'code' | 'peripheral' | 'field' | 'message'
>): string {
  const key = diagnosticMessageKeys[diagnostic.code];
  if (!key) {
    return diagnostic.message;
  }
  return t(key, {
    instance: diagnostic.peripheral ?? 'HPM',
    field: diagnostic.field ?? 'configuration',
  });
}

export function webviewMessages(): Record<string, string> {
  const selected = catalog(activeLocale);
  return Object.fromEntries(
    Object.entries(selected)
      .filter(([key]) => key.startsWith('webview.'))
      .map(([key, value]) => [key.slice('webview.'.length), value]),
  );
}
